def _os_info() -> str:
    try:
        return f"{platform.system()} {platform.release()}（{platform.machine()}）"
    except Exception:
        return sys.platform


def build_system_prompt(
    *,
    config: Any = None,
    workspace: str | None = None,
    model: str | None = None,
    provider: str | None = None,
    tools: list[str] | None = None,
    skill_catalog: str = "",
    memory_block: str = "",
    notes_block: str = "",
    todo_block: str = "",
    goal_block: str = "",
    session_title: str = "",
    subagent: str = "",
    mode: str = "",
    extra: str = "",
) -> str:
    """组装完整系统提示。"""
    parts: list[str] = [f"{IDENTITY}\n\n（当前版本 v{__version__}）", PRINCIPLES]

    # ---- 运行环境 ----
    # ⚠️ 缓存关键：这里的内容会进入「提示前缀」，前缀必须**逐字节稳定**才能命中
    # provider 的 prompt cache（命中后输入便宜 ~90%）。所以：
    #   - 不放时间戳 / 随机数 / 会话 id（会让每次请求前缀都不同 → 命中率 0）
    #   - 只放真正稳定的信息
    # 需要当前时间时，由上层作为「尾部动态消息」注入（见 agent.build_messages 的
    # 时间提醒），而不是改这里。
    env_lines = [
        "## 运行环境",
        f"- 操作系统：{_os_info()}",
        f"- Python：{sys.version.split()[0]}",
        "- 注意：本机可能没有某些常见工具（如 git、docker），"
        "使用前先确认存在，缺失时给出安装建议或用替代方案。",
    ]
    parts.append("\n".join(env_lines))

    parts.append(TOOL_GUIDE)

    # ---- 稳定块（缓存前缀的尾部）----
    # ★ 为什么这几块要**提前**到这里：provider 的 prompt cache 是「前缀匹配」——
    #   从头开始逐字节比对，一旦某处不同、之后全部失效。原先 OUTPUT_STYLE /
    #   思考语言 / 保密 / 安全 排在 goal/todo/memory/skill 这些**每轮都在变**的
    #   动态块之后，于是动态块一变长，后面所有静态文本的字节位置就平移，
    #   前缀缓存整段作废（命中率上不去的成因之一）。
    #   现在把所有静态文本集中在前，动态内容一律放到它们后面。
    parts.append(OUTPUT_STYLE)
    parts.append(_reasoning_lang_block(config))
    parts.append(CONFIDENTIALITY)
    parts.append(SAFETY)

    # ---- 动态块（会随会话/每轮变化，一律排在静态块之后）----
    # ★ 缓存感知投影：动态块内部也要**按变化频率从慢到快**排。
    #   为什么：provider 的 prompt cache 是「前缀逐字节匹配」，从第一个不同的字节起
    #   之后全部失效。如果高频变化的块（每轮都变的 todo / notes）排在低频块
    #   （会话主题、工作区）前面，那么高频块一变，它后面的低频块也跟着作废 ——
    #   命中长度被削掉一大截。
    #   排序原则：几乎不变 → 偶尔变 → 每轮可能变（把最易变的放到最靠近消息尾部）。
    dyn: list[str] = []
    # [1] 最稳定：会话环境与工作模式（换工作区/换模型/切模式才会变）
    info_lines: list[str] = []
    if workspace:
        info_lines.append(f"- 当前工作区：{workspace}")
        info_lines.append("  （相对路径都基于此目录解析；工作区之外的写入会被安全策略拦截）")
    if provider and model:
        info_lines.append(f"- 当前模型：{provider} / {model}")
    if tools:
        info_lines.append(f"- 可用工具：{len(tools)} 个")
    if info_lines:
        dyn.append("## 当前会话环境\n" + "\n".join(info_lines))

    # 工作模式（对话/计划/目标）
    mode_block = WORK_MODES.get(normalize_mode(mode), MODE_AUTO)
    if mode_block:
        dyn.append(mode_block.strip())

    # [2] 较稳定：会话主题与目标（一个会话里基本固定）
    if session_title and session_title not in ("新对话", ""):
        dyn.append(f"<session>当前会话主题：{session_title}</session>")
    if goal_block:
        dyn.append(f"<goal>\n{goal_block}\n</goal>")

    # [3] 会变：技能目录（装/卸技能才变）
    if skill_catalog:
        dyn.append(skill_catalog)

    # [4] 每轮可能变：记忆召回、便签、待办 —— 一律排在动态块末尾
    #   这样前面那几段仍能命中缓存，只有尾部这一小截需要重算。
    if memory_block:
        dyn.append(memory_block)
    if notes_block:
        dyn.append(notes_block)
    if todo_block:
        dyn.append(f"<todos>\n{todo_block}\n</todos>")
    parts.extend(dyn)

    if subagent:
        parts.append(SUBAGENT_PROMPTS.get(subagent, "") or f"<role>你的角色：{subagent}</role>")
    if extra:
        parts.append(extra)

    # 用户自定义追加（放最后，优先级最高）
    user_extra = ""
    if config is not None:
        try:
            user_extra = (config.agent.system_prompt_extra or "").strip()
        except Exception:
            user_extra = ""
    if user_extra:
        parts.append(f"## 用户自定义指令（优先遵循）\n{user_extra}")

    return "\n\n".join(p for p in parts if p and p.strip())


