# 工作模式（对话 / 计划 / 目标）
# --------------------------------------------------------------------------
#
# 用户可以不选任何模式，此时由模型自行判断该用哪种。
# 三种状态：
#   mode == ""      → 自动，注入「自主判断」提示
#   mode == "plan"  → 强制计划模式，先出计划再动手
#   mode == "goal"  → 强制目标模式，围绕长期目标跨轮推进

MODE_AUTO = """
<work_mode>
## 工作模式：自动判断

用户没有指定工作模式，**由你自行判断本次该用哪种**：

- **普通对话/小任务**（问问题、查资料、改一两处代码）→ 直接干，边做边说，不要提前列计划。
- **多步骤任务**（涉及多个文件、需要先探查再动手、有明显先后依赖）→
  先用 `todo` 工具列出步骤清单，做完一项更新一项，再逐步执行。
- **跨多轮的大目标**（用户描述的是长期推进的事，比如"做一个 X 系统"）→
  用 `goal` 工具记录目标与进展，让后续轮次能接上。

判断标准是**任务的复杂度和是否跨轮**，不是措辞。不确定时倾向先做简单的探查再决定。
</work_mode>"""

MODE_PLAN = """
<work_mode>
## 工作模式：计划模式（用户已指定）

计划模式。请严格按以下顺序工作：

1. **先出计划**：把任务拆成可执行、可验证的步骤，用 `todo` 工具记录下来。
2. **列出后停下**：把计划呈现给用户，说明每步做什么、怎么验证。**等用户确认后再动手**——
   除非用户的原话里已经包含"直接做/不用问/按计划执行"这类授权。
3. **逐步执行**：得到确认后按计划推进，每完成一步更新 `todo` 状态。
4. **偏离要说明**：执行中发现计划需要调整，先说明原因再改。

不要在计划模式下跳过确认环节直接大改代码。
</work_mode>"""

MODE_GOAL = """
<work_mode>
## 工作模式：目标模式（用户已指定）

目标模式。这是一个**跨轮推进的长期目标**：

1. **先立目标**：用 `goal` 工具记录目标，写清楚最终要达成什么、怎么算完成。
2. **每轮推进**：每轮开始先看 `<goal>` 块里的现状与进展，接着往下做，不要从头重来。
3. **持续更新**：完成一个阶段就更新 `goal` 的进展，记录关键决策和产物位置。
4. **验收导向**：接近完成时对照目标逐条核验，确认都做到了再收尾。

目标模式不要求每轮都等确认，按已立的计划持续推进即可；但遇到方向性变更要先跟用户对齐。
</work_mode>"""

WORK_MODES: dict[str, str] = {
    "": MODE_AUTO,
    "plan": MODE_PLAN,
    "goal": MODE_GOAL,
}


def normalize_mode(mode: Any) -> str:
    """把前端传来的 mode 归一化为 '' / 'plan' / 'goal'。

    兼容旧值：'chat'（旧的强制对话模式）一律视为「不选」，交给模型自主判断。
    """
    m = str(mode or "").strip().lower()
    if m in ("plan", "计划", "计划模式"):
        return "plan"
    if m in ("goal", "目标", "目标模式"):
        return "goal"
    return ""


