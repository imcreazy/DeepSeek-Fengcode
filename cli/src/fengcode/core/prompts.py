    lang = ""
    if config is not None:
        try:
            lang = (getattr(config.agent, "reasoning_language", "") or "").strip().lower()
        except Exception:
            lang = ""
    if lang in ("", "zh", "auto", "中文"):
        return REASONING_LANG_ZH
    return ""

